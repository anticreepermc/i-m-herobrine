package com.imherobrine.common;

public enum HerobrineAction {
    LIGHTNING,
    APPLY_BUFFS,
    CLEAR_BUFFS,
    TOGGLE_FLY,
    CLEAR_NEARBY_LEAVES,
    PLACE_TREE_TORCHES,
    TELEPORT_TO_AIM,
    BUILD_STRUCTURE,
    SET_LIGHTNING_SINGLE,
    SET_LIGHTNING_BURST,
    SET_LIGHTNING_CHAIN,
    SET_LIGHTNING_RING,
    SET_LIGHTNING_STORM,
    SELECT_SAND_PYRAMID_SMALL,
    SELECT_SAND_PYRAMID_MEDIUM,
    SELECT_SAND_PYRAMID_LARGE,
    SELECT_COBBLE_PYRAMID_SMALL,
    SELECT_COBBLE_PYRAMID_MEDIUM,
    SELECT_COBBLE_PYRAMID_LARGE,
    SELECT_WORD_HEROBRINE,
    SELECT_WORD_STOP,
    SELECT_LETTER_H,
    SELECT_LETTER_E,
    SELECT_LETTER_R,
    SELECT_LETTER_O,
    SELECT_LETTER_B,
    SELECT_LETTER_I,
    SELECT_LETTER_N,
    SELECT_MINE_TUNNEL,
    SELECT_CREEPY_SIGNS,
    SELECT_HEROBRINE_TOTEM,
    ROTATE_STRUCTURE,
    RESET_STRUCTURE_ROTATION,
    BUILD_SELECTED_STRUCTURE;

    public HerobrineAction permissionAction() {
        return switch (this) {
            case SET_LIGHTNING_SINGLE, SET_LIGHTNING_BURST, SET_LIGHTNING_CHAIN, SET_LIGHTNING_RING, SET_LIGHTNING_STORM -> LIGHTNING;
            case SELECT_SAND_PYRAMID_SMALL, SELECT_SAND_PYRAMID_MEDIUM, SELECT_SAND_PYRAMID_LARGE,
                    SELECT_COBBLE_PYRAMID_SMALL, SELECT_COBBLE_PYRAMID_MEDIUM, SELECT_COBBLE_PYRAMID_LARGE,
                    SELECT_WORD_HEROBRINE, SELECT_WORD_STOP, SELECT_LETTER_H, SELECT_LETTER_E, SELECT_LETTER_R,
                    SELECT_LETTER_O, SELECT_LETTER_B, SELECT_LETTER_I, SELECT_LETTER_N, SELECT_MINE_TUNNEL,
                    SELECT_CREEPY_SIGNS, SELECT_HEROBRINE_TOTEM, ROTATE_STRUCTURE, RESET_STRUCTURE_ROTATION,
                    BUILD_SELECTED_STRUCTURE -> BUILD_STRUCTURE;
            default -> this;
        };
    }

    public boolean hasPermissionSetting() {
        return permissionAction() == this;
    }
}
